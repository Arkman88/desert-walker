import fs from 'node:fs/promises'
import { Box3, Mesh, Vector3 } from 'three'
import { prepareRuinGeometry } from '../src/features/locations/ruins/ruinGeometry.ts'
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js'

const root = new URL('../', import.meta.url)
const directory = new URL('public/assets/desert_village_ruins_6_variants/', root)
const manifest = JSON.parse(await fs.readFile(new URL('manifest.json', directory), 'utf8'))
const result = {}
for (const item of manifest) {
  const bytes = await fs.readFile(new URL(item.file, directory))
  const { scene } = await new GLTFLoader().parseAsync(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength), '')
  scene.updateMatrixWorld(true)
  const bounds = new Box3().setFromObject(scene)
  const colliders = []
  const timber = []
  scene.traverse(node => {
    if (!(node instanceof Mesh)) return
    const geometry = prepareRuinGeometry(node)
    geometry.computeBoundingBox()
    const box = geometry.boundingBox
    geometry.dispose()
    if (!box) throw new Error(`Empty ruin piece: ${node.name}`)
    if (/^wood/.test(node.name)) {
      const center = box.getCenter(new Vector3())
      const size = box.getSize(new Vector3())
      timber.push({ name: node.name, center: [center.x, 0, center.z],
        bounds: [-size.x / 2, 0, -size.z / 2, size.x / 2, size.y, size.z / 2],
        fallen: !node.name.startsWith('wood2_') && !(size.x < 0.3 && size.z < 0.3) })
      node.geometry.dispose()
      const materials = Array.isArray(node.material) ? node.material : [node.material]
      materials.forEach(material => material.dispose())
      return
    }
    // Wall proxies stay in model coordinates; timber gets individual terrain transforms at runtime.
    if (box.max.y > 0.5 && /^adobe/.test(node.name)) {
      colliders.push([node.name, ...box.min.toArray(), ...box.max.toArray()])
    }
    node.geometry.dispose()
    ;(Array.isArray(node.material) ? node.material : [node.material]).forEach(material => material.dispose())
  })
  result[item.name] = { bounds: [...bounds.min.toArray(), ...bounds.max.toArray()], colliders, timber }
}
const entries = Object.entries(result).map(([name, asset]) => `  ${name}: {
    bounds: ${JSON.stringify(asset.bounds)},
    colliders: [
${asset.colliders.map(row => '      ' + JSON.stringify(row) + ',').join('\n')}
    ],
    timber: ${JSON.stringify(asset.timber)},
  },`)
const text = '// Generated by node scripts/extract_ruin_bounds.mjs from the six supplied GLBs. Metres, Y up.\nexport const RUIN_BOUNDS = {\n' + entries.join('\n') + '\n} as const\n'
await fs.writeFile(new URL('src/features/locations/ruins/ruinBounds.ts', root), text)
