import assert from 'node:assert/strict'
import { moduleURL } from './module-loader.mjs'
const { createSurvivalStore } = await import(moduleURL('../src/features/survival/survivalStore.ts'))
const { waterMovementSpeed, waterAt } = await import(moduleURL('../src/features/water/water.ts'))
const records = new Map()
const db = { getItem: key => records.get(key) ?? null, setItem: (key, value) => records.set(key, value) }
const store = createSurvivalStore(db, { hideStartBuildings: true })
assert.equal(store.getSprintSpeed(), 13)
assert.equal(waterMovementSpeed(10, null, true, store.getSprintSpeed()), 13)
assert.equal(waterMovementSpeed(10, null, false, store.getSprintSpeed()), 6.5)
store.setSprintSpeed(25)
assert.equal(store.getSprintSpeed(), 25)
assert.equal(waterMovementSpeed(10, null, true, store.getSprintSpeed()), 25)
assert.equal(waterMovementSpeed(10, null, false, store.getSprintSpeed()), 6.5)
const water = { level: 5, depth: 4 }
assert.ok(Math.abs(waterMovementSpeed(5.38, water, true, 25) - 2.4) < 1e-9)
store.setSprintSpeed(NaN)
assert.equal(store.getSprintSpeed(), 25)
store.setSprintSpeed(100)
assert.equal(store.getSprintSpeed(), 40)
store.setSprintSpeed(0)
assert.equal(store.getSprintSpeed(), 6.5)
assert.equal(createSurvivalStore(db).getSprintSpeed(), 13)
assert.equal(waterAt(0, 0), null)
store.announce('Поднята верёвка')
const first = store.getMessageNotice()
assert.equal(store.getSnapshot().message, first.text)
store.announce('Поднята верёвка')
const second = store.getMessageNotice()
assert.ok(second.revision > first.revision, 'Repeated identical messages restart their timer')
store.clearMessage(first.revision)
assert.equal(store.getSnapshot().message, 'Поднята верёвка', 'Old timer cannot remove newer message')
store.clearMessage(second.revision)
assert.equal(store.getSnapshot().message, '')
store.announce('Следующее сообщение')
const last = store.getMessageNotice()
store.clearMessage(second.revision)
assert.equal(store.getSnapshot().message, last.text)
store.clearMessage(last.revision)
assert.equal(store.getSnapshot().message, '')
console.log('PASS: sprint speed limits, normal walking/swimming, session reset, message revisions and stale timer protection.')
